    /**
     * The ink a mode wears, and the side of the brain it sits on.
     *
     * The two halves are told apart by colour and by position, and both are
     * fixed: the fast half is the cyan one on the left, the deep half the
     * emerald one on the right. Colour alone would fail a reader who cannot
     * separate them, so the side is part of the same contract and the
     * component renders both.
     *
     * @return array{accent: string, side: string}
     */
    public static function modeChrome(string $modeKey): array
    {
        return match (self::normalizeModeKey($modeKey)) {
            'system_2' => ['accent' => 'violet', 'side' => 'right'],
            default => ['accent' => 'cyan', 'side' => 'left'],
        };
    }

    /**
     * Normalise a stored mode key; anything unresolvable falls back to
     * System 1 so a typo degrades instead of stranding a mode row.
     */
    public static function normalizeModeKey(?string $key): string
    {
        return array_key_exists((string) $key, self::modes()) ? (string) $key : 'system_1';
    }

    /**
     * Normalise a category's mode affinity — fast, deep, or the both that
     * covers "this is where the two systems meet".
     */
    public static function normalizeAffinity(?string $affinity): string
    {
        return in_array((string) $affinity, ['fast', 'deep', 'both'], true) ? (string) $affinity : 'both';
    }

    /**
     * Normalise a category key to a URL/slug-ish shape so stored keys cannot
     * break the Alpine state or the canvas cluster lookup.
     */
    public static function normalizeCategoryKey(?string $key, int $index): string
    {
        $slug = preg_replace('/[^a-z0-9]+/', '-', strtolower(trim((string) $key)));

        if ($slug === '' || $slug === null || $slug === '-') {
            return 'category-'.($index + 1);
        }

        return trim($slug, '-');
    }
